using System;
using System.IO;
using System.Windows;
using System.Xml;
using Prism.Events;
using TIAOpennessStudio.ViewModels;
using TIAOpennessStudio.Events;

namespace TIAOpennessStudio
{
    // Graph partial: XML graph generation, template merge helpers, and XML utility routines.
    public partial class MainWindow
    {
        private GraphViewModel _graphViewModel;
        
        private void InitGraphModule()
        {
            _graphViewModel = _viewModel.GraphViewModel;
            
            // Subscribe GraphViewModel-specific Prism events (ShowMessageEvent is already subscribed in InitProjectModule, so it is not duplicated here)
            _eventAggregator.GetEvent<SaveFileDialogEvent>().Subscribe(defaultPath => 
            {
                var dialog = new Microsoft.Win32.SaveFileDialog
                {
                    Filter = "XML files (*.xml)|*.xml",
                    FilterIndex = 1,
                    InitialDirectory = System.IO.Path.GetDirectoryName(defaultPath),
                    FileName = System.IO.Path.GetFileName(defaultPath)
                };
                if (dialog.ShowDialog() == true)
                {
                    // Need to fetch the XML document generated by GraphViewModel and save it here;
                    // the real implementation requires more complex coordination.
                }
            }, ThreadOption.UIThread);
            _eventAggregator.GetEvent<SaveFileCompletedEvent>().Subscribe(args => 
            {
                if (args.Success)
                {
                    MessageBox.Show(args.Message, "Generate XML Graph");
                }
                else
                {
                    MessageBox.Show(args.Message, "Exception");
                }
            }, ThreadOption.UIThread);
        }
        
        private void Combine_Click(object sender, RoutedEventArgs e)
        {
            try
            {
                string importPath = Path.Combine(AppDomain.CurrentDomain.BaseDirectory, "Import");
                string file1Path = Path.Combine(importPath, "LAD_TemplateValve_V0.1.xml");
                string file2Path = Path.Combine(importPath, "LAD_Logic_Block_V0.1.xml");
                
                // Delegate business logic to GraphViewModel
                XmlDocument combinedDoc = _graphViewModel.CombineXmlFiles(file1Path, file2Path);
                
                if (combinedDoc != null)
                {
                    combinedDoc.Save(Path.Combine(importPath, "Combined.xml"));
                    MessageBox.Show("Combine completed. Saved to Import\\Combined.xml", "Success");
                }
            }
            catch (Exception ex)
            {
                MessageBox.Show("Error combining files: " + ex.Message, "Error");
            }
        }
    }
}
