using System;
using System.Collections.Generic;
using System.Threading;
using System.Threading.Tasks;

namespace TIAOpennessStudio.Services.Abstractions
{
    // ─────────────────────────────────────────────────────────────────────────
    // Agent <-> user interaction contract.
    //
    // One paradigm for everything an agent needs from a human while it is running:
    //   approve : "may I do X?"            (authorisation gate)
    //   choose  : "which of these?"        (pick one option)
    //   input   : "please tell me Y"       (free text)
    //
    // The contract is transport-agnostic. The cloud path reaches it through the
    // :8001 HTTP server (write gate, ask_user); other callers may reach it directly.
    // NOTE: the local Ollama loop keeps its own onConfirmRequired callback for now
    // and is intentionally NOT wired to this service.
    // ─────────────────────────────────────────────────────────────────────────

    public enum InteractionKind
    {
        Approve,
        Choose,
        Input
    }

    public enum InteractionRisk
    {
        Low,
        Medium,
        /// <summary>Destructive or irreversible. Never offers "remember for this run".</summary>
        High
    }

    /// <summary>How an interaction ended. Callers must distinguish these.</summary>
    public enum InteractionStatus
    {
        /// <summary>The user answered (approved / chose / typed).</summary>
        Answered,
        /// <summary>The user explicitly declined.</summary>
        Denied,
        /// <summary>Nobody answered in time. Treated as a refusal by callers.</summary>
        TimedOut,
        /// <summary>The run was cancelled (stop button, shutdown) while waiting.</summary>
        Cancelled,
        /// <summary>No run scope / no UI available, so the request could not be shown.</summary>
        Unavailable,
        /// <summary>An earlier "remember for this run" approval covered this request.</summary>
        AutoApproved
    }

    public sealed class InteractionOption
    {
        public string Id { get; set; }
        public string Label { get; set; }
        public string Description { get; set; }
    }

    /// <summary>One entry of a merged approval card (several writes queued together).</summary>
    public sealed class InteractionBatchItem
    {
        public string RequestId { get; set; }
        public string Title { get; set; }
        public string Summary { get; set; }
        public InteractionRisk Risk { get; set; }
    }

    public sealed class InteractionRequest
    {
        /// <summary>Assigned by the service when empty.</summary>
        public string Id { get; set; }

        public InteractionKind Kind { get; set; } = InteractionKind.Approve;

        /// <summary>Short headline shown on the drawer.</summary>
        public string Title { get; set; }

        /// <summary>One or two plain-text lines. For approvals this MUST be generated by trusted C# code from facts, not copied from model output.</summary>
        public string Summary { get; set; }

        /// <summary>Optional long text (for example a diff). Rendered collapsed.</summary>
        public string Detail { get; set; }

        /// <summary>Choices for <see cref="InteractionKind.Choose"/>.</summary>
        public IList<InteractionOption> Options { get; set; }

        /// <summary>Placeholder for <see cref="InteractionKind.Input"/>.</summary>
        public string InputHint { get; set; }

        public string DefaultInput { get; set; }

        public InteractionRisk Risk { get; set; } = InteractionRisk.Medium;

        /// <summary>
        /// Capability key for "remember for this run", for example "tia.write.import_block".
        /// Null/empty means the request can never be remembered. Ignored when Risk is High.
        /// </summary>
        public string RememberKey { get; set; }

        /// <summary>Who is asking: tool or agent name, shown to the user.</summary>
        public string Source { get; set; }

        /// <summary>Correlation id of the originating request, when known. Used for audit.</summary>
        public string Rid { get; set; }

        /// <summary>Seconds until the request times out. 0 or less means the service default.</summary>
        public int TimeoutSeconds { get; set; }

        /// <summary>
        /// Seconds until the request is finally refused. Between <see cref="TimeoutSeconds"/> and this the
        /// card stays on screen marked "expired, still approvable", so a slow user never loses a write.
        /// 0 or less means the service default.
        /// </summary>
        public int HardTimeoutSeconds { get; set; }

        /// <summary>
        /// Filled by the service when several queued approvals were merged into this card.
        /// Null/empty means a single request.
        /// </summary>
        public IList<InteractionBatchItem> Batch { get; set; }

        /// <summary>Optional override for the Allow/Submit button text (Approve/Input kinds). Null = default label.</summary>
        public string AllowLabel { get; set; }

        /// <summary>Optional override for the Deny button text (Approve kind). Null = default label.</summary>
        public string DenyLabel { get; set; }

        /// <summary>True when the drawer may offer the "remember for this run" checkbox.</summary>
        public bool CanRemember =>
            Risk != InteractionRisk.High
            && Kind == InteractionKind.Approve
            && !string.IsNullOrWhiteSpace(RememberKey);
    }

    public sealed class InteractionResult
    {
        public InteractionStatus Status { get; set; }

        /// <summary>For Choose: the selected option id. For Input: the typed text. Otherwise null.</summary>
        public string Value { get; set; }

        /// <summary>True when the user ticked "remember for this run".</summary>
        public bool Remember { get; set; }

        /// <summary>Human readable reason, safe to return to the agent.</summary>
        public string Reason { get; set; }

        /// <summary>Approve: allowed. Choose/Input: an answer was supplied.</summary>
        public bool IsPositive =>
            Status == InteractionStatus.Answered || Status == InteractionStatus.AutoApproved;
    }

    /// <summary>
    /// Shows the request and returns what the user did. Implemented by the WPF drawer.
    /// It must never throw for user actions; it completes the task with the outcome.
    /// </summary>
    public interface IInteractionPresenter
    {
        /// <summary>
        /// Display one request and complete with the user's decision. The implementation must
        /// complete (or observe <paramref name="ct"/>) so the service can always tear it down.
        /// </summary>
        Task<InteractionResult> PresentAsync(InteractionRequest request, int queuePosition, int queueLength, CancellationToken ct);

        /// <summary>Remove anything currently shown for this request id (timeout / cancel).</summary>
        void Dismiss(string requestId);

        /// <summary>
        /// Re-render the currently shown card after the service merged another queued request into it.
        /// Implementations must ignore requests that are not the card on screen.
        /// </summary>
        void Update(InteractionRequest request);
    }

    /// <summary>One entry of the audit trail. Emitted for every request, whatever the outcome.</summary>
    public sealed class InteractionAuditRecord
    {
        public DateTime TimestampUtc { get; set; }
        public string RequestId { get; set; }
        public string RunId { get; set; }
        public string Rid { get; set; }
        public InteractionKind Kind { get; set; }
        public string Source { get; set; }
        public string Title { get; set; }
        public InteractionRisk Risk { get; set; }
        public InteractionStatus Status { get; set; }
        public string Value { get; set; }
        public bool Remembered { get; set; }
        public long WaitedMs { get; set; }
    }

    /// <summary>
    /// Single entry point for agent-to-user interaction. Thread-safe.
    /// </summary>
    public interface IUserInteractionService
    {
        /// <summary>
        /// Open a run scope. Interactions made while a run is active belong to it, and "remember for this run"
        /// approvals live only as long as it. Dispose the returned handle when the run ends: that cancels
        /// every pending interaction of the run and clears its remembered approvals.
        /// </summary>
        IDisposable BeginRun(string runId, CancellationToken runToken);

        /// <summary>Id of the run that interactions are currently attributed to, or null.</summary>
        string ActiveRunId { get; }

        /// <summary>
        /// True while any request is on screen or queued. Run-level watchdogs (the chat timeout) use it to stop
        /// the clock while a person is deciding: a user thinking for two minutes is not a hung model.
        /// </summary>
        bool HasPending { get; }

        /// <summary>
        /// Ask the user. Never throws for normal outcomes; inspect <see cref="InteractionResult.Status"/>.
        /// Without an active run the result is Unavailable, unless <paramref name="allowWithoutRun"/> is true
        /// (used for approvals that must still be gated, for example external MCP clients).
        /// </summary>
        Task<InteractionResult> RequestAsync(InteractionRequest request, CancellationToken ct = default, bool allowWithoutRun = false);

        /// <summary>Raised for every finished request, for audit logging.</summary>
        event Action<InteractionAuditRecord> Audited;
    }
}
