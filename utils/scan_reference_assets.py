#!/usr/bin/env python3
"""Scan the repository's reference assets into one manifest + human index.

Why: the repo carries several overlapping reference sets (official TIA exports, XSDs,
embedded GRAPH templates, agent-facing samples). Without one inventory it is impossible
to tell which file is authoritative, which is a byte-for-byte copy, which TIA version it
actually proves, and which files the runtime depends on.

Usage:
  python utils/scan_reference_assets.py
      -> docs/assets/reference_assets.json   (machine readable)
      -> docs/assets/REFERENCE_INDEX.md      (human readable)

  python utils/scan_reference_assets.py --samples
      -> additionally regenerates docs/samples/manifest.json

  python utils/scan_reference_assets.py --lad-parts
      -> additionally regenerates
         TIAAgent/tools/openness_samples/lad_part_catalog.md
         (Part vocabulary extracted from the official V15.1 LAD export)

The script never moves or deletes files. It only classifies them.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import sys
from collections import Counter, defaultdict
from datetime import datetime, timezone
from pathlib import Path
from xml.etree import ElementTree

REPO = Path(__file__).resolve().parents[1]

# Directories that are never treated as reference assets and are skipped while looking
# for code references (vendor dumps, build output, caches).
SKIP_DIRS = {
    ".git", ".vs", ".kiro", ".pytest_cache", ".screenshots", ".tmp_audit",
    ".tmp_stats", ".tmp_verify", "bin", "obj", "node_modules", "__pycache__",
    "python", "_pydeps", "site-packages", "Library Types", "GeneratedCode",
    "competition", "StandardsKbTool",
}

# Directories whose files are reference assets.
ASSET_ROOTS = (
    "docs/PublicAPI",
    "TIAOpennessStudio/Templates",
    "docs/samples",
    "TIAAgent/tools/openness_samples",
)

# Files that are generated by this script (never counted as a code reference).
GENERATED_OUTPUTS = {
    "docs/assets/reference_assets.json",
    "docs/assets/REFERENCE_INDEX.md",
    "docs/samples/manifest.json",
    "TIAAgent/tools/openness_samples/lad_part_catalog.md",
}

CODE_EXTENSIONS = {".cs", ".py", ".xaml", ".csproj", ".ps1", ".md", ".json", ".bat"}

# The scanner itself mentions every asset name; counting that as a consumer would make
# every asset look "active". Treat it as tooling, not as a code reference.
REFERENCE_SCANNERS = {"utils/scan_reference_assets.py"}


def rel_of(path: Path) -> str:
    return path.relative_to(REPO).as_posix()


def sha256_of(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def classify(rel: str, path: Path) -> str:
    if rel.startswith("docs/PublicAPI"):
        if path.suffix.lower() == ".xsd":
            return "xsd"
        if path.suffix.lower() == ".dll":
            return "assembly"
        if path.suffix.lower() == ".xml":
            return "api_doc"
        return "install_file"
    if rel.startswith("TIAOpennessStudio/Templates/"):
        return "embedded_template"
    if rel.startswith("docs/samples/"):
        return "sample_library"
    if rel.startswith("TIAAgent/tools/openness_samples/"):
        return "agent_sample"
    return "unknown"


_VERSION_FROM_DIR = re.compile(r"^V(\d+)(?:\.(\d+))?(?:\.AddIn)?$")
_VERSION_FROM_NAME = re.compile(r"V(\d+)_(\d+)", re.IGNORECASE)


def version_of(rel: str, path: Path) -> str:
    for part in path.parts:
        match = _VERSION_FROM_DIR.match(part)
        if match:
            return match.group(1) + ("." + match.group(2) if match.group(2) else "")
    match = _VERSION_FROM_NAME.search(path.name)
    if match:
        return match.group(1) + "." + match.group(2)
    if "V14SP1" in path.name.upper():
        return "14 SP1"
    return ""


def verified_of(klass: str, version: str) -> str:
    if klass == "xsd":
        return "schema_spec"
    if klass in {"assembly", "api_doc"}:
        return "official_api_doc"
    if klass == "install_file":
        return "official_install_file"
    if klass == "embedded_template":
        # Only the two genuine TIA exports are ground truth; the Step/Transition/Branch
        # files are hand-authored fragments.
        return "real_export" if version in {"15.1", "14 SP1"} else "fragment"
    if klass == "agent_sample":
        return "project_note"
    if klass == "sample_library":
        return "see docs/samples/manifest.json"
    return "unverified"


def source_of(klass: str) -> str:
    if klass in {"xsd", "assembly", "api_doc", "install_file"}:
        return "official_tia_install"
    if klass == "sample_library":
        return "mixed"
    if klass in {"embedded_template", "agent_sample"}:
        return "project"
    return "unknown"


def iter_assets() -> list[Path]:
    found: list[Path] = []
    for root_rel in ASSET_ROOTS:
        root = REPO / root_rel
        if not root.exists():
            continue
        for dirpath, dirnames, filenames in os.walk(root):
            dirnames[:] = sorted(d for d in dirnames if d not in SKIP_DIRS)
            for name in sorted(filenames):
                candidate = Path(dirpath) / name
                if rel_of(candidate) in GENERATED_OUTPUTS:
                    continue
                found.append(candidate)
    return found


def collect_text_index() -> dict[str, list[str]]:
    """basename -> files that mention it (code references)."""
    index: dict[str, list[str]] = defaultdict(list)
    for dirpath, dirnames, filenames in os.walk(REPO):
        dirnames[:] = sorted(d for d in dirnames if d not in SKIP_DIRS)
        for name in sorted(filenames):
            path = Path(dirpath) / name
            if path.suffix.lower() not in CODE_EXTENSIONS:
                continue
            rel = rel_of(path)
            if rel in GENERATED_OUTPUTS or rel in REFERENCE_SCANNERS:
                continue
            try:
                text = path.read_text(encoding="utf-8", errors="ignore")
            except Exception:
                continue
            if not text:
                continue
            for token in set(re.findall(r"[A-Za-z0-9_.\- ]{3,120}\.(?:xml|xsd|dll|md)", text)):
                token = token.strip()
                if token:
                    index[token].append(rel)
    return index


def used_by(basename: str, text_index: dict[str, list[str]], self_rel: str) -> list[str]:
    hits = text_index.get(basename, [])
    return sorted({hit for hit in hits if hit != self_rel})


def code_consumers(used: list[str]) -> list[str]:
    """Consumers that actually load the file (code/tooling), not docs that merely cite it."""
    return [u for u in used if not u.lower().endswith(".md")]


def empty_dirs() -> list[str]:
    """Directories under docs/PublicAPI that contain no files anywhere below them."""
    result = []
    root = REPO / "docs/PublicAPI"
    if not root.exists():
        return result
    for dirpath, dirnames, filenames in os.walk(root):
        if filenames:
            continue
        has_file_below = any(
            files
            for _, _, files in os.walk(Path(dirpath))
            if files
        )
        if not has_file_below:
            result.append(rel_of(Path(dirpath)))
    return sorted(set(result))


PATH_IN_TEXT = re.compile(r"(?:docs|TIAOpennessStudio/XML)/(?:[^\s`\"'<>|，。；、()）\]]+)")

IGNORE_FILE = "docs/reference_assets_ignore.txt"


def load_ignores() -> set[tuple[str, str]]:
    """Deliberately missing references (planned templates, removed dirs)."""
    path = REPO / IGNORE_FILE
    ignored: set[tuple[str, str]] = set()
    if not path.exists():
        return ignored
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#") or "|" not in line:
            continue
        doc, referenced = line.split("|", 1)
        ignored.add((doc.strip(), referenced.strip()))
    return ignored


def broken_doc_references() -> list[dict[str, str]]:
    issues: list[dict[str, str]] = []
    seen: set[tuple[str, str]] = set()
    ignored = load_ignores()
    doc_roots = [REPO / "docs", REPO]
    for root in doc_roots:
        if not root.exists():
            continue
        for dirpath, dirnames, filenames in os.walk(root):
            dirnames[:] = [d for d in dirnames if d not in SKIP_DIRS]
            if root == REPO:
                dirnames[:] = [d for d in dirnames if d != "docs"]
            for name in sorted(filenames):
                if not name.lower().endswith(".md"):
                    continue
                path = Path(dirpath) / name
                rel = rel_of(path)
                if rel in GENERATED_OUTPUTS:
                    continue
                try:
                    text = path.read_text(encoding="utf-8", errors="ignore")
                except Exception:
                    continue
                for match in PATH_IN_TEXT.finditer(text):
                    candidate = match.group(0).rstrip(".,;:")
                    candidate = candidate.replace("\\", "/")
                    key = (rel, candidate)
                    if key in seen:
                        continue
                    seen.add(key)
                    if key in ignored:
                        continue
                    if not (REPO / candidate).exists():
                        kind = (
                            "asset_reference"
                            if candidate.startswith(("docs/PublicAPI", "TIAOpennessStudio/XML"))
                            else "doc_link"
                        )
                        issues.append(
                            {"doc": rel, "referenced_path": candidate, "kind": kind}
                        )
    return issues


def build_manifest() -> dict:
    text_index = collect_text_index()
    assets = []
    for path in iter_assets():
        rel = rel_of(path)
        klass = classify(rel, path)
        version = version_of(rel, path)
        used = used_by(path.name, text_index, rel)
        assets.append(
            {
                "path": rel,
                "class": klass,
                "version": version,
                "source": source_of(klass),
                "size": path.stat().st_size,
                "sha256": sha256_of(path),
                "duplicate_of": "",
                "used_by": used,
                "code_used_by": code_consumers(used),
                "verified": verified_of(klass, version),
                "status": "",
            }
        )

    assets.sort(key=lambda a: a["path"])

    # Duplicates: the sample library is canonical; an embedded template that still duplicates
    # it is the copy that must eventually be removed.
    class_rank = {"sample_library": 0, "xsd": 1, "assembly": 2, "api_doc": 3,
                  "embedded_template": 4, "agent_sample": 5, "doc": 6, "unknown": 7}
    by_hash: dict[str, list[dict]] = defaultdict(list)
    for asset in assets:
        by_hash[asset["sha256"]].append(asset)
    for group in by_hash.values():
        if len(group) < 2:
            continue
        group.sort(key=lambda a: (class_rank.get(a["class"], 9), a["path"]))
        canonical = group[0]
        for asset in group[1:]:
            asset["duplicate_of"] = canonical["path"]

    for asset in assets:
        # A copy that the runtime still loads must never be reported as a deletable duplicate.
        if asset["code_used_by"]:
            asset["status"] = "active"
        elif asset["duplicate_of"]:
            asset["status"] = "duplicate"
        elif asset["class"] in {"xsd", "assembly", "api_doc", "install_file", "agent_sample", "sample_library"}:
            asset["status"] = "reference"
        elif asset["class"] == "embedded_template":
            asset["status"] = "embedded"
        else:
            asset["status"] = "unreferenced"

    empty = empty_dirs()
    broken = broken_doc_references()

    versions_with_schemas = sorted(v for v in {a["version"] for a in assets if a["class"] == "xsd"} if v)

    summary = {
        "generated_at": datetime.now(timezone.utc).astimezone().isoformat(timespec="seconds"),
        "asset_count": len(assets),
        "by_class": dict(Counter(a["class"] for a in assets)),
        "by_status": dict(Counter(a["status"] for a in assets)),
        "versions_with_xsd": versions_with_schemas,
        "empty_dirs": empty,
        "broken_doc_references": broken,
    }
    return {"summary": summary, "assets": assets}


def write_json(manifest: dict) -> Path:
    out = REPO / "docs/assets/reference_assets.json"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    return out


def write_index(manifest: dict) -> Path:
    summary = manifest["summary"]
    assets = manifest["assets"]
    lines: list[str] = []
    lines.append("# Reference asset index")
    lines.append("")
    lines.append("> Generated by `python utils/scan_reference_assets.py`. Do not hand-edit;")
    lines.append("> re-run the scanner after adding, moving or deleting reference files.")
    lines.append("")
    lines.append(f"Generated: {summary['generated_at']}")
    lines.append("")
    lines.append("## Summary")
    lines.append("")
    lines.append(f"- Assets: **{summary['asset_count']}**")
    lines.append(f"- Versions with XSD: {', '.join(summary['versions_with_xsd']) or '(none)'}")
    lines.append("- Block samples: `docs/samples/` — see `docs/samples/manifest.json` for versions, "
                 "provenance and verification status.")
    lines.append("- By class: " + ", ".join(f"{k}={v}" for k, v in sorted(summary["by_class"].items())))
    lines.append("- By status: " + ", ".join(f"{k}={v}" for k, v in sorted(summary["by_status"].items())))
    lines.append("")

    lines.append("## Issues")
    lines.append("")
    duplicates = [a for a in assets if a["status"] == "duplicate"]
    lines.append(f"### Duplicates ({len(duplicates)} copies of {len({a['duplicate_of'] for a in duplicates})} file(s))")
    lines.append("")
    if duplicates:
        grouped: dict[str, list[str]] = defaultdict(list)
        for asset in duplicates:
            grouped[asset["duplicate_of"]].append(asset["path"])
        lines.append("| Canonical copy | Extra copies | Paths |")
        lines.append("|---|---|---|")
        for canonical, copies in sorted(grouped.items()):
            lines.append(
                f"| `{canonical}` | {len(copies)} | "
                + ", ".join(f"`{c}`" for c in copies)
                + " |"
            )
    else:
        lines.append("None.")
    lines.append("")
    lines.append("> Note: duplicates inside `docs/PublicAPI` are part of the TIA export itself "
                 "(`V16.AddIn` / `V17.AddIn` mirror the main version folders). Keep them as exported; "
                 "this list is for identification, not a deletion plan.")
    lines.append("")

    kept_duplicates = [a for a in assets if a["duplicate_of"] and a["code_used_by"]]
    lines.append(f"### Duplicate but still loaded at runtime ({len(kept_duplicates)}) — do not delete")
    lines.append("")
    if kept_duplicates:
        lines.append("| Copy | Identical to | Loaded by |")
        lines.append("|---|---|---|")
        for asset in kept_duplicates:
            lines.append(
                f"| `{asset['path']}` | `{asset['duplicate_of']}` | "
                + ", ".join(f"`{u}`" for u in asset["code_used_by"][:3])
                + " |"
            )
    else:
        lines.append("None.")
    lines.append("")

    lines.append(f"### Empty directories ({len(summary['empty_dirs'])})")
    lines.append("")
    if summary["empty_dirs"]:
        for path in summary["empty_dirs"]:
            lines.append(f"- `{path}`")
    else:
        lines.append("None.")
    lines.append("")

    asset_issues = [i for i in summary["broken_doc_references"] if i["kind"] == "asset_reference"]
    doc_issues = [i for i in summary["broken_doc_references"] if i["kind"] != "asset_reference"]
    lines.append(f"### Broken asset references in docs ({len(asset_issues)})")
    lines.append("")
    if asset_issues:
        lines.append("| Doc | Referenced path that does not exist |")
        lines.append("|---|---|")
        for issue in asset_issues:
            lines.append(f"| `{issue['doc']}` | `{issue['referenced_path']}` |")
    else:
        lines.append("None.")
    lines.append("")

    lines.append(f"### Broken doc-to-doc links ({len(doc_issues)})")
    lines.append("")
    if doc_issues:
        lines.append("| Doc | Referenced path that does not exist |")
        lines.append("|---|---|")
        for issue in doc_issues:
            lines.append(f"| `{issue['doc']}` | `{issue['referenced_path']}` |")
    else:
        lines.append("None.")
    lines.append("")

    lines.append("## Assets by class")
    lines.append("")
    for klass in ("xsd", "assembly", "api_doc", "embedded_template",
                  "sample_library", "agent_sample", "install_file"):
        group = [a for a in assets if a["class"] == klass]
        if not group:
            continue
        lines.append(f"### {klass} ({len(group)})")
        lines.append("")
        lines.append("| Path | Version | Verified | Status | Used by |")
        lines.append("|---|---|---|---|---|")
        for asset in group:
            used = ", ".join(f"`{u}`" for u in asset["used_by"][:3]) or "—"
            extra = " +" if len(asset["used_by"]) > 3 else ""
            lines.append(
                f"| `{asset['path']}` | {asset['version'] or '—'} | {asset['verified']} | "
                f"{asset['status']} | {used}{extra} |"
            )
        lines.append("")

    lines.append("## Status legend")
    lines.append("")
    lines.append("- `active` — loaded by code/a tool (a copy that is still loaded also gets `active`); keep it.")
    lines.append("- `reference` — authoritative reference, used by convention/pattern rather than a literal path.")
    lines.append("- `embedded` — bundled as an EmbeddedResource; runtime template.")
    lines.append("- `duplicate` — byte-identical copy of the file named in `duplicate_of`, not loaded by the runtime.")
    lines.append("- `unreferenced` — project-authored file nothing points at; review before keeping.")
    lines.append("")
    lines.append("## Verified legend")
    lines.append("")
    lines.append("- `real_export` — a genuine TIA export (ground truth for that version).")
    lines.append("- `schema_spec` — official XSD; proves element order/enums, not runtime behaviour.")
    lines.append("- `official_api_doc` — official Openness assembly + XML doc.")
    lines.append("- `official_install_file` — auxiliary file shipped with the TIA install (PDF, .bat, etc.).")
    lines.append("- `fragment` — hand-authored XML fragment, not an export; never cite it as ground truth.")
    lines.append("- `project_note` — project-authored note, not a TIA export.")
    lines.append("- `see docs/samples/manifest.json` — sample provenance/status is per file; this "
                 "index does not duplicate it.")
    lines.append("")

    out = REPO / "docs/assets/REFERENCE_INDEX.md"
    out.write_text("\n".join(lines), encoding="utf-8")
    return out


def _local(tag: str) -> str:
    return tag.split("}")[-1]


def build_lad_part_catalog() -> Path:
    sample = REPO / "docs/samples/V15.1/LAD/LAD_V0.1.xml"
    if not sample.exists():
        raise SystemExit(f"official LAD sample not found: {rel_of(sample)}")

    tree = ElementTree.parse(sample)
    root = tree.getroot()

    parts: list[ElementTree.Element] = [e for e in root.iter() if _local(e.tag) == "Part"]

    # UIds are scoped per CompileUnit (every network restarts at 21), so a global UId->Part
    # map would attribute one network's pins to another network's Part.
    pins: dict[str, set[str]] = defaultdict(set)
    for unit in (e for e in root.iter() if _local(e.tag) == "SW.Blocks.CompileUnit"):
        uid_to_name: dict[str, str] = {}
        for part in unit.iter():
            if _local(part.tag) != "Part":
                continue
            uid = part.get("UId")
            name = part.get("Name")
            if uid and name:
                uid_to_name[uid] = name
        for wire in unit.iter():
            if _local(wire.tag) != "Wire":
                continue
            for child in wire:
                if _local(child.tag) != "NameCon":
                    continue
                uid = child.get("UId")
                pin = child.get("Name")
                if uid in uid_to_name and pin:
                    pins[uid_to_name[uid]].add(pin)

    children: dict[str, set[str]] = defaultdict(set)
    for part in parts:
        name = part.get("Name")
        for child in part:
            children[name].add(_local(child.tag))

    calls: list[str] = []
    for call in root.iter():
        if _local(call.tag) != "Call":
            continue
        info = next((c for c in call if _local(c.tag) == "CallInfo"), None)
        calls.append((info.get("Name") if info is not None else None) or "(unnamed)")

    counts = Counter(p.get("Name") for p in parts if p.get("Name"))
    networks = len([e for e in root.iter() if _local(e.tag) == "SW.Blocks.CompileUnit"])
    local_con = 0
    for access in root.iter():
        if _local(access.tag) == "Access" and access.get("Scope") == "LocalVariable":
            local_con += 1

    lines: list[str] = []
    lines.append("# LAD Part catalog (extracted, not hand-written)")
    lines.append("")
    lines.append("> Generated by `python utils/scan_reference_assets.py --lad-parts` from the official")
    lines.append("> V15.1 export `docs/samples/V15.1/LAD/LAD_V0.1.xml`.")
    lines.append("> Do not hand-edit; regenerate after replacing the sample.")
    lines.append("")
    lines.append(f"- Source: official TIA V15.1 export, {networks} networks")
    lines.append("- Pins below are the pins **actually wired in this sample**, not the full XSD pin set.")
    lines.append(f"- Local-variable accesses in this sample: **{local_con}** "
                 "(so even the official LAD sample cannot serve as a `#variable` template).")
    lines.append("- Called blocks in this sample: "
                 + (", ".join(f"`{c}`" for c in calls) if calls else "(none — no Call parts)"))
    lines.append("")
    lines.append("| Part Name | Occurrences | Wired pins | Nested elements |")
    lines.append("|---|---|---|---|")
    for name, count in counts.most_common():
        pin_text = ", ".join(sorted(pins.get(name, set()))) or "—"
        child_text = ", ".join(sorted(children.get(name, set()))) or "—"
        lines.append(f"| `{name}` | {count} | {pin_text} | {child_text} |")
    lines.append("")
    lines.append("## How to use this catalog")
    lines.append("")
    lines.append("1. A new LAD `body` may only use Part names listed above until another name is proven")
    lines.append("   by `compile_block` on a real import.")
    lines.append("2. `NameCon` in a `Wire` names the pin; `UId` points at the Part. Only these pin names")
    lines.append("   appeared in the sample — other pins may exist but are unverified.")
    lines.append("3. A negated contact appears as its own `NContact` Part in this export; a hand-built")
    lines.append("   `Contact` + `<Negated Name=\"operand\"/>` is a second form (seen in project block")
    lines.append("   `ATUO_1`). Both must be verified per CPU family before being relied on.")
    lines.append("4. This catalog says nothing about CPU availability: S7-300/400 vs 1200 vs 1500 can")
    lines.append("   differ. Treat `compile_block` as the only authority.")
    lines.append("")

    out = REPO / "TIAAgent/tools/openness_samples/lad_part_catalog.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines), encoding="utf-8")
    return out


