def _schema_bucket(version: str) -> str:
    match = re.match(r"(\d+)", version or "")
    if not match:
        return "unknown"
    return "<=15.1" if int(match.group(1)) <= 15 else ">=16"


def _derive_sample_facts(path: Path) -> dict:
    """Language/kind/features extracted from the XML itself."""
    root = ElementTree.parse(path).getroot()

    language = ""
    block_kind = ""
    parts: set[str] = set()
    scopes: set[str] = set()
    features: set[str] = set()
    members_by_section: dict[str, int] = defaultdict(int)

    for element in root.iter():
        name = _local(element.tag)
        if name == "ProgrammingLanguage" and not language:
            language = (element.text or "").strip().upper()
        elif name == "Access":
            scope = (element.get("Scope") or "").strip()
            if scope:
                scopes.add(scope)
        elif name == "Part":
            part = (element.get("Name") or "").strip()
            if part:
                parts.add(part)
        elif name == "Negated":
            features.add("negated_contact")
        elif name == "Section":
            section = (element.get("Name") or "").strip()
            members = sum(1 for child in element if _local(child.tag) == "Member")
            # "None" sections exist in GRAPH alarm settings and are not block interface members.
            if section and section.lower() != "none" and members:
                members_by_section[section] += members
        if name == "SW.Types.PlcStruct" and not block_kind:
            block_kind = "UDT"
        elif name.startswith("SW.Blocks.") and not block_kind:
            block_kind = name.split(".")[-1]
            if block_kind in {"GlobalDB", "InstanceDB"}:
                block_kind = "DB"

    if not language:
        lowered = {_local(e.tag) for e in root.iter()}
        if "FlgNet" in lowered:
            language = "LAD"
        elif "StructuredText" in lowered:
            language = "SCL"
        elif "StatementList" in lowered:
            language = "STL"
        elif "Graph" in lowered:
            language = "GRAPH"
        elif block_kind == "UDT":
            language = "UDT"
        elif block_kind == "DB":
            language = "DB"

    for scope in scopes:
        key = scope.lower()
        if key == "localvariable":
            features.add("local_variable")
        elif key == "globalvariable":
            features.add("global_variable")
        elif key == "typedconstant":
            features.add("typed_constant")
        elif key == "literalconstant":
            features.add("literal_constant")

    for part in parts:
        mapped = PART_FEATURE_MAP.get(part)
        if mapped:
            features.add(mapped)
        elif part.startswith("Cmp"):
            features.add("compare")

    for section, count in members_by_section.items():
        features.add("interface_" + section.lower())

    networks = sum(1 for e in root.iter() if _local(e.tag) == "SW.Blocks.CompileUnit")
    if networks == 1:
        features.add("single_network")
    elif networks > 1:
        features.add("multi_network")

    steps = sum(1 for e in root.iter() if _local(e.tag) == "Step" or _local(e.tag) == "StepRef")
    transitions = sum(1 for e in root.iter() if _local(e.tag) == "Transition" or _local(e.tag) == "TransitionRef")
    branches = sum(1 for e in root.iter() if _local(e.tag) == "Branches")
    jumps = sum(1 for e in root.iter() if _local(e.tag) == "LinkType" and (e.text or "").strip().lower() == "jump")
    if language == "GRAPH":
        features.add("graph_sequence")
        if branches:
            features.add("graph_branch")
        if jumps:
            features.add("graph_jump")
        if transitions:
            features.add("graph_transition")

    calls = sum(1 for e in root.iter() if _local(e.tag) == "Call")
    if calls:
        features.add("block_call")

    memory_layout = next(
        ((e.text or "").strip() for e in root.iter() if _local(e.tag) == "MemoryLayout"),
        "",
    )
    if memory_layout.lower() == "optimized":
        features.add("db_optimized")
    elif memory_layout.lower() == "standard":
        features.add("db_standard")
    if any(_local(e.tag) == "InstanceOfName" for e in root.iter()):
        features.add("instance_db")

    return {
        "language": language,
        "block_kind": block_kind,
        "features": sorted(features),
        "parts": sorted(parts),
        "networks": networks,
        "steps": steps,
        "transitions": transitions,
    }


def _load_annotations() -> dict[str, dict]:
    path = REPO / SAMPLES_ANNOTATIONS
    if not path.exists():
        return {}
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except Exception:
        return {}
    return data.get("samples", {}) if isinstance(data, dict) else {}


def _sample_files() -> list[Path]:
    """Every block sample under docs/samples/V<ver>/<language>/."""
    samples_root = REPO / SAMPLES_ROOT
    if not samples_root.exists():
        return []
    return sorted(samples_root.rglob("*.xml"))


def build_sample_entries() -> list[dict]:
    annotations = _load_annotations()
    entries: list[dict] = []
    used_ids: set[str] = set()

    for path in _sample_files():
        rel = rel_of(path)
        version = version_of(rel, path)
        facts = _derive_sample_facts(path)
        base_id = f"{version or 'unknown'}.{facts['language'] or 'UNK'}.{path.stem}"
        sample_id = base_id
        suffix = 2
        while sample_id in used_ids:
            sample_id = f"{base_id}_{suffix}"
            suffix += 1
        used_ids.add(sample_id)

        note = annotations.get(sample_id, {})
        entries.append(
            {
                "id": sample_id,
                "path": rel,
                "version": version,
                "schema_bucket": _schema_bucket(version),
                "language": facts["language"],
                "block_kind": facts["block_kind"],
                "provenance": note.get("provenance", "unknown"),
                "status": note.get("status", "unverified"),
                "role": note.get("role", "reference"),
                "features": facts["features"],
                "parts": facts["parts"],
                "networks": facts["networks"],
                "size": path.stat().st_size,
                "sha256": sha256_of(path),
                "source_block": note.get("source_block", ""),
                "notes": note.get("notes", ""),
            }
        )

    entries.sort(key=lambda e: (e["version"], e["language"], e["id"]))
    return entries


def write_samples() -> Path:
    entries = build_sample_entries()

    by_sha: dict[str, list[dict]] = defaultdict(list)
    for entry in entries:
        by_sha[entry["sha256"]].append(entry)
    for group in by_sha.values():
        if len(group) < 2:
            continue
        group.sort(key=lambda e: ({"exported": 0, "schema_valid": 1}.get(e["status"], 2), e["path"]))
        canonical = group[0]
        for entry in group[1:]:
            entry["duplicate_of"] = canonical["path"]
    for entry in entries:
        entry.setdefault("duplicate_of", "")

    feature_counts: dict[str, int] = Counter()
    for entry in entries:
        for feature in entry["features"]:
            feature_counts[feature] += 1

    manifest = {
        "schema": 2,
        "generated_at": datetime.now(timezone.utc).astimezone().isoformat(timespec="seconds"),
        "summary": {
            "count": len(entries),
            "by_version": dict(sorted(Counter(e["version"] for e in entries).items())),
            "by_language": dict(sorted(Counter(e["language"] or "unknown" for e in entries).items())),
            "by_provenance": dict(sorted(Counter(e["provenance"] for e in entries).items())),
            "by_status": dict(sorted(Counter(e["status"] for e in entries).items())),
            "by_role": dict(sorted(Counter(e["role"] for e in entries).items())),
            "features": dict(sorted(feature_counts.items())),
            "duplicates": sum(1 for e in entries if e["duplicate_of"]),
        },
        "samples": entries,
    }
    manifest_path = REPO / SAMPLES_MANIFEST
    manifest_path.parent.mkdir(parents=True, exist_ok=True)
    manifest_path.write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    return manifest_path


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--lad-parts", action="store_true",
                        help="also regenerate the LAD Part catalog from the official V15.1 sample")
    parser.add_argument("--samples", action="store_true",
                        help="also regenerate docs/samples/manifest.json")
    args = parser.parse_args()

    manifest = build_manifest()
    json_path = write_json(manifest)
    index_path = write_index(manifest)
    print(f"wrote {rel_of(json_path)} ({manifest['summary']['asset_count']} assets)")
    print(f"wrote {rel_of(index_path)}")
    if args.lad_parts:
        catalog = build_lad_part_catalog()
        print(f"wrote {rel_of(catalog)}")
    if args.samples:
        samples_manifest = write_samples()
        count = len(json.loads(samples_manifest.read_text(encoding="utf-8"))["samples"])
        print(f"wrote {rel_of(samples_manifest)} ({count} samples)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
